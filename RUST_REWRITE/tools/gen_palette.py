"""Writes crates/zenko-art/src/palette_data.rs from zenko.py's final _PAL_BASE, FUR, ROBES and COATS (run from repo root)."""
import os, sys, tempfile
sys.dont_write_bytecode = True
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.environ["APPDATA"] = tempfile.mkdtemp()
sys.path.insert(0, ROOT)
import zenko as Z  # noqa: E402

out = ["//! Colour palettes, generated by RUST_REWRITE/tools/gen_palette.py from zenko.py's _PAL_BASE, FUR, ROBES and COATS.\n",
       "pub const PAL_BASE: &[(u8, &str)] = &["]
out += ["    (b'%s', \"%s\")," % (k, v) for k, v in Z._PAL_BASE.items() if v]
out += ["];\n", "/// FUR[name] = palette letters that differ from PAL_BASE (after _fur()'s N<-n, s<-S, p<-P defaults).",
        "pub const FUR: &[(&str, &[(u8, &str)])] = &["]
for name, p in Z.FUR.items():
    diff = [(k, v) for k, v in p.items() if v and Z._PAL_BASE.get(k) != v]
    out.append("    (\"%s\", &[%s])," % (name, ", ".join("(b'%s', \"%s\")" % kv for kv in diff)))
out += ["];\n", "pub struct Robe { pub key: &'static str, pub name: &'static str, pub hours: i32, pub motif: &'static str, pub cols: &'static [(u8, &'static str)] }",
        "pub const ROBES: &[Robe] = &["]
for k, r in Z.ROBES.items():
    cols = ", ".join("(b'%s', \"%s\")" % (c, r[c]) for c in r if len(c) == 1)
    out.append("    Robe { key: \"%s\", name: \"%s\", hours: %d, motif: \"%s\", cols: &[%s] }," % (k, r["name"], r["hours"], r["motif"], cols))
out += ["];\n", "/// (config key, label, FUR name) - zenko.py COATS",
        "pub const COATS: &[(&str, &str, &str)] = &[" + ", ".join("(\"%s\", \"%s\", \"%s\")" % (a, b, c or "") for a, b, c in Z.COATS) + "];",
        "pub const COAT_KEYS: &[u8] = b\"%s\";" % Z.COAT_KEYS]
open(os.path.join(ROOT, "RUST_REWRITE", "crates", "zenko-art", "src", "palette_data.rs"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print("palette_data.rs written")
