n_items = n_ported = 0
out.append("## Module-level functions and data")
out.append("")
out.append("| line | kind | name | lines | status | note |")
out.append("|---:|---|---|---:|---|---|")
for n in tree.body:
    if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)):
        n_items += 1
        p = n.name in PORTED
        n_ported += p
        out.append("| %d | def | `%s` | %d | %s | %s |" % (n.lineno, n.name, n.end_lineno - n.lineno + 1, "ported" if p else "",
                                                       doc1(n).replace("|", "/")))
    elif isinstance(n, ast.Assign) and n.end_lineno - n.lineno >= 20:
        out.append("| %d | data | `%s` | %d | | |" % (n.lineno, ast.unparse(n.targets[0])[:40], n.end_lineno - n.lineno + 1))
out.append("")
for n in tree.body:
    if not isinstance(n, ast.ClassDef):
        continue
    bases = ", ".join(ast.unparse(b) for b in n.bases)
    out.append("## class %s(%s)  (line %d, %d lines)" % (n.name, bases, n.lineno, n.end_lineno - n.lineno + 1))
    if doc1(n):
        out.append("")
        out.append(doc1(n))
    out.append("")
    out.append("| line | method | lines | status | note |")
    out.append("|---:|---|---:|---|---|")
    for m in n.body:
        if isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef)):
            n_items += 1
            p = ("%s.%s" % (n.name, m.name)) in PORTED
            n_ported += p
            out.append("| %d | `%s` | %d | %s | %s |" % (m.lineno, m.name, m.end_lineno - m.lineno + 1, "ported" if p else "",
                                                     doc1(m).replace("|", "/")))
    out.append("")
out.insert(4, "**%d functions/methods, %d ported so far (%.1f%%).**" % (n_items, n_ported, 100.0 * n_ported / n_items))
out.insert(5, "")
